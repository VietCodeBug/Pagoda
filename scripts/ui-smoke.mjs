import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const base = process.env.SMOKE_URL || 'http://localhost:3000';
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: process.env.SMOKE_SOFTWARE_RENDERER === '1' ? ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] : [] });
const errors = [];
const results = [];
let mobile;
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
page.on('pageerror', e => { if(!errors.includes(e.message)){errors.push(e.message);console.error(e.stack);} });
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
try {
  await page.goto(base, { waitUntil: 'domcontentloaded', timeout: 90000 });
  console.log('Web loaded; waiting for models and physics.');
  await page.getByRole('heading', { name: /Một khoảng/ }).waitFor({ timeout: 90000 });
  await page.locator('.loading-veil').waitFor({ state: 'hidden', timeout: 90000 });
  await page.screenshot({ path: 'artifacts/desktop-entry.png' });
  results.push('3D assets loaded, entry rendered');
  await page.getByRole('button', { name: 'Cài đặt', exact: true }).click();
  await page.getByRole('button', { name: /Low.*Nhẹ nhàng/ }).click();
  await page.getByRole('button', { name: 'Đóng', exact: true }).click();
  await page.getByLabel('Tên của bạn', { exact: true }).count().then(async count => { if (count) await page.getByLabel('Tên của bạn', { exact: true }).fill('QA Browser'); else await page.locator('#guest-name').fill('QA Browser'); });
  await page.getByRole('button', { name: 'Chọn Thanh Trúc' }).click();
  await page.getByLabel('Chọn phòng', { exact: true }).selectOption('lotus-3');
  await page.getByRole('button', { name: 'Bước vào chùa', exact: true }).click();
  await page.locator('.room-badge').filter({ hasText: /1\/20/ }).waitFor({ timeout: 30000 });
  await page.waitForTimeout(750);
  results.push('Guest entry and real room connection');
  await page.screenshot({ path: 'artifacts/desktop-game.png' });
  const marker = page.locator('.minimap:not(.large) svg > circle').last();
  const zBefore = Number(await marker.getAttribute('cy'));
  await page.keyboard.down('KeyW');
  for(let i=0;i<12&&Number(await marker.getAttribute('cy'))>=zBefore-2;i++)await page.waitForTimeout(500);
  await page.keyboard.up('KeyW');
  const zAfter=Number(await marker.getAttribute('cy'));
  assert.ok(zAfter < zBefore - 2, `W must move the actual avatar toward the temple (${zBefore} -> ${zAfter})`);
  for (const key of ['KeyS', 'KeyA', 'KeyD', 'KeyW']) {
    await page.keyboard.down(key);
    await page.waitForTimeout(1200);
    await page.keyboard.up(key);
  }
  results.push('Actual avatar displacement and stable direction reversals');
  await page.locator('.action-bar button[title="Ngồi thiền"]').click();
  await page.locator('.interaction-prompt').filter({ hasText: 'Đứng dậy' }).waitFor();
  await page.waitForTimeout(300);
  const seatedZ = Number(await marker.getAttribute('cy'));
  await page.keyboard.down('KeyW');
  await page.waitForTimeout(1300);
  await page.keyboard.up('KeyW');
  assert.ok(Math.abs(Number(await marker.getAttribute('cy')) - seatedZ) < .7, 'Meditation must lock movement');
  await page.keyboard.press('KeyE');
  await page.locator('.interaction-prompt').filter({ hasText: 'Đứng dậy' }).waitFor({ state: 'hidden' });
  results.push('Meditation movement lock and E to stand');
  await page.keyboard.press('KeyM');
  await page.getByRole('dialog', { name: 'Một nơi để khám phá' }).waitFor();
  await page.screenshot({ path: 'artifacts/map.png' });
  await page.keyboard.press('Escape');
  await page.keyboard.press('Enter');
  await page.getByLabel('Tin nhắn', { exact: true }).fill('Xin chào từ bản kiểm tra.');
  await page.getByLabel('Tin nhắn', { exact: true }).press('Enter');
  await page.locator('.chat-log').getByText('Xin chào từ bản kiểm tra.', { exact: true }).waitFor();
  results.push('WASD, map keyboard shortcut, realtime chat');
  await page.getByRole('button', { name: 'Cài đặt', exact: true }).click();
  await page.getByRole('switch', { name: 'Đêm hoa đăng' }).click();
  await page.getByRole('button', { name: 'Đóng', exact: true }).click();
  await page.screenshot({ path: 'artifacts/desktop-night.png' });
  results.push('Night lighting switch');
  await page.keyboard.down('ShiftLeft');
  await page.keyboard.down('KeyW');
  const altarPrompt = page.locator('.interaction-prompt').filter({ hasText: 'Dâng hương' });
  for(let i=0; i<12 && !(await altarPrompt.isVisible()); i++) await page.waitForTimeout(750);
  await page.keyboard.up('KeyW');
  await page.keyboard.up('ShiftLeft');
  await altarPrompt.waitFor({ state: 'visible', timeout: 5000 });
  await page.keyboard.press('KeyE');
  await page.getByRole('dialog', { name: 'Gửi một lời bình an' }).waitFor();
  await page.getByRole('textbox', { name: 'Lời nguyện', exact: true }).fill('QA UI: Mong một ngày bình an.');
  await page.getByRole('button', { name: 'Dâng hương & gửi lời nguyện' }).click();
  await page.locator('.toast').filter({ hasText: 'Lời nguyện riêng tư của bạn đã được lưu.' }).waitFor();
  await page.waitForTimeout(800);
  await page.screenshot({ path: 'artifacts/incense.png' });
  results.push('E altar interaction, prayer persisted, incense ritual');
  mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  mobile.on('pageerror', e => { if(!errors.includes(e.message)){errors.push(e.message);console.error(e.stack);} });
  await mobile.goto(base, { waitUntil: 'domcontentloaded', timeout: 90000 });
  await mobile.getByRole('heading', { name: /Một khoảng/ }).waitFor();
  await mobile.locator('.loading-veil').waitFor({ state: 'hidden', timeout: 90000 });
  await mobile.screenshot({ path: 'artifacts/mobile-entry.png' });
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile horizontal overflow');
  await mobile.locator('#guest-name').fill('QA Mobile');
  await mobile.getByLabel('Chọn phòng', { exact: true }).selectOption('lotus-3');
  await mobile.getByRole('button', { name: 'Bước vào chùa', exact: true }).click();
  await mobile.locator('.room-badge').filter({ hasText: /2\/20/ }).waitFor({ timeout: 30000 });
  await page.locator('.room-badge').filter({ hasText: /2\/20/ }).waitFor();
  await mobile.locator('.joystick').waitFor({ state: 'visible' });
  const mobileMarker = mobile.locator('.minimap:not(.large) svg > circle').last();
  const mobileZBefore = Number(await mobileMarker.getAttribute('cy'));
  const stick = await mobile.locator('.joystick').boundingBox();
  await mobile.mouse.move(stick.x + stick.width/2, stick.y + stick.height/2);
  await mobile.mouse.down();
  await mobile.mouse.move(stick.x + stick.width/2, stick.y + stick.height/2 - 32);
  await mobile.waitForTimeout(2000);
  await mobile.mouse.up();
  assert.ok(Number(await mobileMarker.getAttribute('cy')) < mobileZBefore - 1, 'Joystick must move the actual avatar');
  await mobile.screenshot({ path: 'artifacts/mobile-game.png' });
  results.push('Mobile responsive entry, joystick, two browser players in same room');
  await writeFile('artifacts/ui-results.json', JSON.stringify({ results, errors }, null, 2));
  assert.deepEqual(errors, [], 'Browser reported errors');
  console.log(JSON.stringify({ passed: results, errors }));
} catch (error) {
  await page.screenshot({ path: 'artifacts/ui-failure.png' }).catch(() => {});
  if(mobile) await mobile.screenshot({ path: 'artifacts/ui-mobile-failure.png' }).catch(() => {});
  await writeFile('artifacts/ui-results.json', JSON.stringify({ results, errors, failure: String(error) }, null, 2));
  throw error;
} finally { await browser.close(); }
